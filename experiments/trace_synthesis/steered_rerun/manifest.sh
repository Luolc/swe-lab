#!/usr/bin/env bash
# Regenerate MANIFEST.md: what this round froze, where, and its sha256.
#
# The frozen trees are large agent conversations and stay out of git by repo
# rule; they also stay out of every *worktree*, because `git worktree remove`
# deletes gitignored content without warning and that is how the previous
# round's evidence was lost (docs/conventions.md -> Hazards). So the repo keeps
# this: a pointer plus a per-file digest, which is enough to prove a tree is
# the one the report was written from.
#
# Usage: manifest.sh [artifact-root]
set -euo pipefail

root="${1:-/home/ubuntu/dev/swe-lab-artifacts/trace_synthesis}"
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/MANIFEST.md"

{
  echo "# Frozen artifacts — manifest"
  echo
  echo "Generated by [\`manifest.sh\`](manifest.sh) on $(date -Is)."
  echo
  echo "Everything below lives at \`$root\` — **outside every git worktree**, on"
  echo "purpose. Large traces stay out of git (repo rule), and a gitignored path"
  echo "*inside* a worktree does not survive \`git worktree remove\`"
  echo "([hazards](../../../docs/conventions.md#hazards-learned-the-hard-way))."
  echo
  for tree in "$root"/*/; do
    [ -d "$tree" ] || continue
    name="$(basename "$tree")"
    echo "## \`$name\`"
    echo
    echo "- files: $(find "$tree" -type f | wc -l), size: $(du -sh "$tree" | cut -f1)"
    echo "- tree digest (sha256 of the sorted per-file manifest):"
    echo "  \`$(cd "$tree" && find . -type f -exec sha256sum {} + | sort -k2 | sha256sum | cut -d' ' -f1)\`"
    echo
    echo '```'
    (cd "$tree" && find . -type f -exec sha256sum {} + | sort -k2 | sed 's|\./||')
    echo '```'
    echo
  done
} > "$out"

echo "wrote $out"
