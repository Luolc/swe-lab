#!/usr/bin/env bash
# Regenerate MANIFEST.md: what this round froze, where, and its sha256.
#
# The frozen trees are large agent conversations and stay out of git by repo
# rule; they also stay out of every *worktree*, because `git worktree remove`
# deletes gitignored content without warning and that is how the previous
# round's evidence was lost (docs/conventions.md -> Hazards). So the repo keeps
# this: a pointer plus a per-file digest, which is enough to prove a tree is
# the one the report was written from.
#
# Usage: manifest.sh [artifact-root]
set -euo pipefail

# What MANIFEST.md prints for a root: the operator's home rendered as `~`.
# The manifest is committed and `docs/conventions.md` forbids a home path in a
# committed record, so writing the root itself would put one back on every
# regeneration. The pointer's job is to say where the trees live relative to a
# home directory, which `~` does without naming the machine or its user.
#
# Only $HOME itself and paths *under* it are rewritten. Matching a raw string
# prefix instead also fires on a sibling whose name merely starts with the home
# directory's characters -- the home path with a suffix such as `-artifacts`
# appended, which is a perfectly valid place to keep them. That came out as
# `~-artifacts/...`: neither the requested root nor a home-relative pointer, and
# the manifest would have recorded an artifact location that does not exist.
#
# Its own step, and reachable as `manifest.sh --print-label <root>`, so the
# boundary can be tested without walking a multi-gigabyte tree.
home_label() {
  local path="$1"
  if [ -z "${HOME:-}" ]; then
    printf '%s\n' "$path"
  elif [ "$path" = "$HOME" ]; then
    printf '~\n'
  elif [ "${path#"$HOME"/}" != "$path" ]; then
    printf '~/%s\n' "${path#"$HOME"/}"
  else
    printf '%s\n' "$path"
  fi
}

if [ "${1:-}" = "--print-label" ]; then
  home_label "${2:?usage: manifest.sh --print-label <root>}"
  exit 0
fi

root="${1:-$HOME/dev/swe-lab-artifacts/trace_synthesis}"
root_label="$(home_label "$root")"
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/MANIFEST.md"

{
  echo "# Frozen artifacts — manifest"
  echo
  echo "Generated by [\`manifest.sh\`](manifest.sh) on $(date -Is)."
  echo
  echo "Everything below lives at \`$root_label\` — **outside every git worktree**, on"
  echo "purpose. Large traces stay out of git (repo rule), and a gitignored path"
  echo "*inside* a worktree does not survive \`git worktree remove\`"
  echo "([hazards](../../../docs/conventions.md#hazards-learned-the-hard-way))."
  echo
  for tree in "$root"/*/; do
    [ -d "$tree" ] || continue
    name="$(basename "$tree")"
    echo "## \`$name\`"
    echo
    echo "- files: $(find "$tree" -type f | wc -l), size: $(du -sh "$tree" | cut -f1)"
    echo "- tree digest (sha256 of the sorted per-file manifest):"
    echo "  \`$(cd "$tree" && find . -type f -exec sha256sum {} + | sort -k2 | sha256sum | cut -d' ' -f1)\`"
    echo
    echo '```'
    (cd "$tree" && find . -type f -exec sha256sum {} + | sort -k2 | sed 's|\./||')
    echo '```'
    echo
  done
} > "$out"

echo "wrote $out"
